decisions_text = read(decisions, "docs/agent/integrations.md") if decisions.exists() else None
in_section, header = False, None
for line in (decisions_text or "").splitlines():
    if line.startswith("## "):
        in_section, header = line.strip() == "## AI setup audit", None
        continue
    if not in_section or not line.lstrip().startswith("|"):
        header = None if in_section and not line.strip() else header
        continue
    cells = table_cells(line)
    if header is None:
        header = cells
    elif {"Kind", "Location", "Decision"} <= set(header) and not set("".join(cells)) <= set("-: "):
        row = dict(zip(header, cells))
        if row.get("Decision", "").lower() == "keep":
            accepted.add((row.get("Kind", ""), row.get("Location", "")))
findings = {("info", k, l, f"(accepted) {d}") if lv == "warning" and (k, l) in accepted else (lv, k, l, d) for lv, k, l, d in findings}

for level, kind, location, detail in sorted(findings, key=lambda f: (f[0] != "warning", f[1], f[2], f[3])):
    print(f"{level}\t{kind}\t{location}\t{detail}")
raise SystemExit(1 if any(f[0] == "warning" for f in findings) else 0)
