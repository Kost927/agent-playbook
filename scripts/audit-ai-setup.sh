#!/usr/bin/env bash
# Audit existing AI setup (instructions, skills, MCP servers, hooks, methodology tools) in a target
# repository. Read-only: never writes, executes, or installs anything.
#
# Usage: scripts/audit-ai-setup.sh [--global] <target-dir>
#   --global  also read user-level setup (names and descriptions only). Use only with the owner's permission.
# Output: one finding per line, "<level>\t<kind>\t<location>\t<detail>", level warning or info.
# Exit: 0 no warnings, 1 at least one warning, 2 usage error.
set -euo pipefail

global=0
while [[ $# -gt 1 ]]; do
  case "$1" in
    --global) global=1; shift ;;
    *) break ;;
  esac
done
if [[ $# -ne 1 || ! -d "$1" ]]; then
  echo "usage: $0 [--global] <target-dir>" >&2
  exit 2
fi

target_root="$(cd "$1" && pwd)"

python3 -I - "$target_root" "$global" <<'PY'
import json
import os
import re
import sys
from pathlib import Path

target, use_global = Path(sys.argv[1]), sys.argv[2] == "1"
findings = set()
SKIPPED_DIRS = {".git", "node_modules", "vendor", "third_party", ".venv", "venv", "dist", "build", "__pycache__", ".tox"}
SKILL_ROOTS = {".agents", ".claude", ".cursor", ".codex"}
INSTRUCTION_NAMES = {"AGENTS.md", "CLAUDE.md", "GEMINI.md", ".cursorrules", ".windsurfrules", ".clinerules"}
MARKERS = {".specify/": "Spec Kit", "openspec/": "OpenSpec", ".planning/": "GSD", "docs/superpowers/": "Superpowers"}
SECRET_KEY = re.compile(r"TOKEN|KEY|SECRET|PASSWORD|AUTH")
REFERENCE = re.compile(r"\$\{[^}]+\}|\$[A-Za-z_][A-Za-z0-9_]*")
LINK = re.compile(r"(?<!!)\[[^\]]*\]\(([^)\s]+)[^)]*\)")
ERRORS = (OSError, ValueError, TypeError, AttributeError, UnicodeError, RecursionError)


def clean(text):
    return re.sub(r"[\t\r\n\x00-\x1f]+", " ", str(text)).strip()


def add(level, kind, location, detail=""):
    findings.add((level, kind, clean(location), clean(detail)))


def unreadable(label, error):
    add("info", "unreadable", label, type(error).__name__)


def as_dict(value):
    return value if isinstance(value, dict) else {}


def as_list(value):
    return value if isinstance(value, list) else []


def rel(path):
    return path.relative_to(target).as_posix()


def read(path, label):
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except ERRORS as error:
        unreadable(label, error)
        return None


JSONC_STRING = re.compile(r'"(?:[^"\\]|\\.)*"?', re.S)
JSONC_GAP = re.compile(r"(?:\s|//[^\n]*|/\*.*?\*/)*", re.S)


def strip_jsonc(text):
    """Drop // and /* */ comments and trailing commas outside strings (Cursor accepts JSON with comments)."""
    out, i, n = [], 0, len(text)
    while i < n:
        char = text[i]
        if char == '"':
            end = JSONC_STRING.match(text, i).end()
            out.append(text[i:end]); i = end
        elif text.startswith("//", i):
            end = text.find("\n", i); i = n if end < 0 else end
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2); i = n if end < 0 else end + 2
        elif char == ",":
            if not text.startswith(("}", "]"), JSONC_GAP.match(text, i + 1).end()):
                out.append(char)
            i += 1
        else:
            out.append(char); i += 1
    return "".join(out)


def load_json(path, label, jsonc=False):
    text = read(path, label)
    if text is None:
        return None
    try:
        return json.loads(strip_jsonc(text) if jsonc else text)
    except ERRORS as error:
        unreadable(label, error)
        return None


def walk(root):
    for directory, subdirs, files in os.walk(root):
        subdirs[:] = sorted(d for d in subdirs if d not in SKIPPED_DIRS)
        yield Path(directory), subdirs, files


def outside_fences(text):
    lines, fence = [], None
    for line in text.splitlines():
        marker = re.match(r"^ {0,3}(`{3,}|~{3,})", line)
        if fence:
            if marker and marker.group(1)[0] == fence[0] and len(marker.group(1)) >= len(fence):
                fence = None
            continue
        if marker:
            fence = marker.group(1)
            continue
        lines.append(line)
    return lines


def frontmatter_split(content):
    match = re.match(rb"^---\r?\n(.*?)\r?\n---\r?\n?", content, re.S)
    return (match.group(1), content[match.end():]) if match else (b"", content)


def skill_name(content, folder):
    head, _ = frontmatter_split(content)
    name = re.search(rb"^name:[ \t]*['\"]?([^'\"\r\n]+?)['\"]?[ \t]*\r?$", head, re.M)
    return name.group(1).decode("utf-8", "replace") if name else folder


def is_playbook_skill(content):
    """The generated header from bootstrap.md step 4.1, or an older header naming agent-playbook."""
    return re.match(rb"\s*<!--[^\n]*(Generated by the Agent Playbook|agent-playbook)", frontmatter_split(content)[1]) is not None


# Skills: name -> list of (location label, content bytes, is user level).
skills = {}
repo_skill_files = []


def collect_skills(skills_dir, label, user=False):
    try:
        skill_files = sorted(skills_dir.glob("*/SKILL.md"))
    except ERRORS as error:
        unreadable(label(skills_dir / "x" / "SKILL.md"), error)
        return
    for skill_file in skill_files:
        try:
            content = skill_file.read_bytes()
        except ERRORS as error:
            unreadable(label(skill_file), error)
            continue
        skills.setdefault(skill_name(content, skill_file.parent.name), []).append((label(skill_file), content, user))
        if not user:
            repo_skill_files.append(skill_file)


for directory, _, _ in walk(target):
    if directory.name == "skills" and directory.parent.name in SKILL_ROOTS:
        collect_skills(directory, lambda p: rel(p.parent))

# Instruction files.
instruction_files = []
for directory, _, files in walk(target):
    for name in sorted(files):
        path = directory / name
        if name in INSTRUCTION_NAMES or (name.endswith(".mdc") and directory.name == "rules" and directory.parent.name == ".cursor"):
            instruction_files.append(path)
copilot = target / ".github" / "copilot-instructions.md"
if copilot.exists():
    instruction_files.append(copilot)
for path in instruction_files:
    add("info", "instruction-sources", rel(path))

texts = {}
for path in instruction_files + repo_skill_files:
    if path.is_symlink() and not path.exists():
        add("info", "unreadable", rel(path), "dangling symlink")
        continue
    if not path.is_symlink():
        text = read(path, rel(path))
        if text is not None:
            texts[path] = text

for claude in [p for p in instruction_files if p.name == "CLAUDE.md"]:
    agents = claude.with_name("AGENTS.md")
    if not agents.exists() or claude not in texts:
        continue
    # Same rule as check-target.sh: a fence line at any indent toggles; exactly one import outside fences.
    imports, in_fence = 0, False
    for line in texts[claude].splitlines():
        if line.lstrip().startswith(("```", "~~~")):
            in_fence = not in_fence
        elif not in_fence and line.strip() == "@AGENTS.md":
            imports += 1
    if imports == 0:
        add("warning", "claude-import-missing", rel(claude), "does not import its sibling AGENTS.md")
    elif imports > 1:
        add("warning", "claude-import-missing", rel(claude), f"imports AGENTS.md {imports} times; expected once")

# Broken relative links in instruction files and repository skills.
for path, text in sorted(texts.items()):
    for line in outside_fences(text):
        for href in LINK.findall(line):
            if re.match(r"^[a-z][a-z0-9+.-]*:", href, re.I) or href.startswith("#"):
                continue
            local = href.split("#", 1)[0].split("?", 1)[0]
            destination = target / local.lstrip("/") if local.startswith("/") else path.parent / local
            if not destination.exists():
                add("warning", "broken-reference", rel(path), local)

# MCP servers: name -> list of (location label, definition key, env dict).
servers = {}


def definition_key(server):
    return json.dumps([server.get("command") or server.get("url"), as_list(server.get("args"))], sort_keys=True, default=str)


def add_server(name, server, label):
    env = {**as_dict(server.get("env")), **as_dict(server.get("headers"))}
    servers.setdefault(str(name), []).append((label, definition_key(server), env))


def read_json_mcp(path, label, jsonc=False):
    data = load_json(path, label, jsonc)
    for name, server in sorted(as_dict(as_dict(data).get("mcpServers")).items()):
        if isinstance(server, dict):
            add_server(name, server, label)


def read_jsonc_mcp(path, label):
    read_json_mcp(path, label, jsonc=True)


def toml_value(text):
    """Parse one TOML value (string, literal string, array, inline table, scalar); return (value, rest)."""
    text = text.lstrip()
    if text.startswith('"'):
        match = re.match(r'"((?:[^"\\]|\\.)*)"', text)
        if not match:
            raise ValueError("unterminated string")
        return json.loads(match.group(0)), text[match.end():]
    if text.startswith("'"):
        end = text.find("'", 1)
        if end < 0:
            raise ValueError("unterminated literal string")
        return text[1:end], text[end + 1:]
    if text.startswith("["):
        items, rest = [], text[1:]
        while True:
            rest = re.sub(r"^(\s|,|#[^\n]*)*", "", rest)
            if rest.startswith("]"):
                return items, rest[1:]
            if not rest:
                raise ValueError("unterminated array")
            item, rest = toml_value(rest)
            items.append(item)
    if text.startswith("{"):
        table, rest = {}, text[1:]
        while True:
            rest = rest.lstrip(" \t,")
            if rest.startswith("}"):
                return table, rest[1:]
            key = re.match(r'("(?:[^"\\]|\\.)*"|\'[^\']*\'|[A-Za-z0-9_-]+)\s*=', rest)
            if not key:
                raise ValueError("bad inline table")
            value, rest = toml_value(rest[key.end():])
            table[key.group(1).strip("\"'")] = value
    match = re.match(r"[^\s,\]}#]+", text)
    if not match:
        raise ValueError("bad value")
    return match.group(0), text[match.end():]


def read_toml_mcp(path, label):
    text = read(path, label)
    if text is None:
        return
    parsed, section, pending = {}, None, ""
    try:
        for raw in text.splitlines():
            line = raw if pending else raw.strip()
            if not pending and (not line or line.startswith("#")):
                continue
            if not pending and line.startswith("["):
                header = re.match(r'^\[\s*mcp_servers\.("(?:[^"\\]|\\.)*"|\'[^\']*\'|[A-Za-z0-9_-]+)(?:\.(env|headers))?\s*\]', line)
                section = (header.group(1).strip("\"'"), header.group(2)) if header else None
                if section:
                    parsed.setdefault(section[0], {})
                continue
            pending += raw + "\n"
            key = re.match(r'^\s*("(?:[^"\\]|\\.)*"|\'[^\']*\'|[A-Za-z0-9_.-]+)\s*=\s*', pending)
            if not key:
                raise ValueError("bad key")
            try:
                value, _ = toml_value(pending[key.end():])
            except ValueError:
                if pending.count("\n") > 200:
                    raise
                continue
            pending = ""
            if not section:
                continue
            name, sub = section
            field = key.group(1).strip("\"'")
            if sub:
                parsed[name].setdefault(sub, {})[field] = value
            else:
                parsed[name][field] = value
        if pending:
            raise ValueError("unterminated value")
    except ERRORS as error:
        unreadable(label, error)
        return
    for name, server in sorted(parsed.items()):
        add_server(name, server, label)


for name, reader in ((".mcp.json", read_json_mcp), (".cursor/mcp.json", read_jsonc_mcp), (".codex/config.toml", read_toml_mcp)):
    path = target / name
    if path.exists() or path.is_symlink():
        reader(path, name)

# Hooks: event and the program's base name only, never arguments.
for name in (".claude/settings.json", ".claude/settings.local.json"):
    path = target / name
    if not path.exists():
        continue
    settings = as_dict(load_json(path, name))
    for event, entries in sorted(as_dict(settings.get("hooks")).items()):
        for entry in as_list(entries):
            for hook in as_list(as_dict(entry).get("hooks")):
                command = str(as_dict(hook).get("command") or as_dict(hook).get("type") or "?").split()
                program = os.path.basename(command[0]) if command else "?"
                add("info", "hooks", name, f"{event}: {program}")
    for plugin, enabled in sorted(as_dict(settings.get("enabledPlugins")).items()):
        if enabled is True and str(plugin).startswith("superpowers@"):
            add("info", "methodology-tools", name, f"Superpowers ({plugin})")

# The playbook's shared maps and the task artifacts the workflow commits (tests and acceptance plan records) must be
# committable: warn when git would ignore new files in docs/agent/, or only in docs/agent/tasks/. Probe ordinary Markdown
# paths with --no-index, so neither tracked files nor dotfile rules change the answer. Run git with a clean environment
# and fsmonitor disabled, so nothing configured in the target repository executes.
import subprocess
git_env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
git_env.update({"LC_ALL": "C", "LANG": "C"})


def git_ignores(relative):
    probe = subprocess.run(
        ["git", "-c", "core.fsmonitor=false", "-C", str(target), "check-ignore", "--no-index", "-q", relative],
        capture_output=True, text=True, timeout=20, env=git_env,
    )
    if probe.returncode not in (0, 1) and "not a git repository" not in probe.stderr:
        add("info", "unreadable", "git", "check-ignore failed")
    return probe.returncode == 0


try:
    if git_ignores("docs/agent/audit-probe.md"):
        add("warning", "agent-docs-ignored", "docs/agent/", "git ignores new files in docs/agent/; re-include it (for example `docs/*` then `!docs/agent/` when docs/ itself is ignored)")
    elif git_ignores("docs/agent/tasks/audit-probe.md"):
        add("warning", "agent-tasks-ignored", "docs/agent/tasks/", "git ignores task folders, so the tests and acceptance plan commits cannot include task artifacts; re-include them or record where those artifacts go")
except FileNotFoundError:
    add("info", "unreadable", "git", "git unavailable")
except ERRORS + (subprocess.SubprocessError,) as error:
    unreadable("git", error)

# Methodology markers.
for marker, tool in MARKERS.items():
    if (target / marker).is_dir():
