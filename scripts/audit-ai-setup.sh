if use_global:
    home = Path(os.environ.get("HOME", "/nonexistent"))
    for source, relative in (("agents-skills", ".agents/skills"), ("claude-skills", ".claude/skills"), ("codex-skills", ".codex/skills"), ("cursor-skills", ".cursor/skills")):
        if (home / relative).is_dir():
            collect_skills(home / relative, lambda p, s=source: f"user-level:{s}:{p.parent.name}", user=True)
    user_settings = home / ".claude/settings.json"
    enabled = as_dict(as_dict(load_json(user_settings, "user-level:claude-settings")).get("enabledPlugins")) if user_settings.exists() else {}
    installed_file = home / ".claude/plugins/installed_plugins.json"
    installed = as_dict(as_dict(load_json(installed_file, "user-level:claude-plugins")).get("plugins")) if installed_file.exists() else {}
    for plugin, on in sorted(enabled.items()):
        if on is not True:
            continue
        if str(plugin).startswith("superpowers@"):
            add("info", "methodology-tools", f"user-level:claude-plugin:{plugin}", "Superpowers")
        for install in as_list(installed.get(plugin)):
            install = as_dict(install)
            install_path = install.get("installPath")
            if not isinstance(install_path, str) or not os.path.isabs(install_path):
                continue
            project = install.get("projectPath")
            if install.get("scope") in ("project", "local") and (not isinstance(project, str) or Path(project).resolve() != target.resolve()):
                continue
            if (Path(install_path) / "skills").is_dir():
                version = install.get("version")
                label = f"user-level:claude-plugin:{plugin}" + (f"@{version}" if isinstance(version, str) and version else "")
                collect_skills(Path(install_path) / "skills", lambda p, label=label: label, user=True)
    for relative, reader, label in ((".cursor/mcp.json", read_jsonc_mcp, "user-level:cursor-mcp"), (".codex/config.toml", read_toml_mcp, "user-level:codex-mcp")):
        if (home / relative).exists():
            reader(home / relative, label)

# Cross-location comparisons.
for name, copies in sorted(skills.items()):
    if len(copies) < 2:
        continue
    places = ", ".join(sorted({label for label, _, _ in copies}))
    repo = [content for _, content, user in copies if not user]
    user = [content for _, content, user in copies if user]
    if len(set(repo)) > 1 or (not repo and len(set(user)) > 1):
        add("warning", "skill-duplicate", f"skill:{name}", places)
    elif repo and user and set(user) != set(repo) and not all(is_playbook_skill(c) for c in repo + user):
        add("warning", "skill-shadow", f"skill:{name}", places)
    else:
        add("info", "skill-mirror", f"skill:{name}", places)

for name, entries in sorted(servers.items()):
    for label, _, env in entries:
        for key, value in sorted(env.items()):
            if SECRET_KEY.search(str(key).upper()) and isinstance(value, str) and value.strip() and not REFERENCE.search(value):
                add("warning", "mcp-literal-secret", f"mcp:{name}", f"{label}: {key} holds a literal value")
    if len(entries) > 1:
        places = ", ".join(sorted(label for label, _, _ in entries))
        level = "info" if len({definition for _, definition, _ in entries}) == 1 else "warning"
        add(level, "mcp-duplicate", f"mcp:{name}", places)


def table_cells(line):
    cells, current, in_code = [], "", False
    for char in line.strip().strip("|"):
        if char == "`":
            in_code = not in_code
        if char == "|" and not in_code:
            cells.append(current.strip().strip("`"))
            current = ""
        else:
            current += char
    cells.append(current.strip().strip("`"))
    return cells


# Findings the owner decided to keep are reported as accepted and do not fail the audit.
